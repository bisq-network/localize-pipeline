#!/bin/bash
# Setup script for automated Docker cleanup cron job
# This script installs a weekly cron job that runs scripts/docker-cleanup.sh
#
# Usage:
#   sudo ./scripts/setup-cron-cleanup.sh [PROJECT_PATH]
#
# Example:
#   sudo ./scripts/setup-cron-cleanup.sh /opt/localize-pipeline
#
# PROJECT_PATH is a checkout of this repository (default: the current
# directory). The cron job runs scripts/docker-cleanup.sh inside that
# checkout, so a deployment that checks out a newer commit also updates the
# cleanup. Nothing is copied into the checkout: scripts/deploy-build.sh
# refuses to build from a checkout with untracked files.
#
# What this script does:
#   1. Checks that PROJECT_PATH contains scripts/docker-cleanup.sh
#   2. Creates or replaces the weekly cron job in /etc/cron.weekly/
#   3. Runs the cleanup once as a test
#
# Requirements:
#   - Must be run as root (for cron installation)
#   - Docker must be installed
#
# CLEANUP_CRON_DIR overrides the cron directory (default /etc/cron.weekly).

set -euo pipefail

CRON_DIR="${CLEANUP_CRON_DIR:-/etc/cron.weekly}"

# Root is needed to write the cron directory.
if [ "$EUID" -ne 0 ] && [ ! -w "$CRON_DIR" ]; then
    echo "Error: This script must be run as root (use sudo)" >&2
    exit 1
fi

# Get project path from argument or use current directory
PROJECT_PATH="${1:-$(pwd)}"

if [ ! -d "$PROJECT_PATH" ]; then
    echo "Error: Project path does not exist: $PROJECT_PATH" >&2
    exit 1
fi
# Use an absolute path, so the cron job works from any directory.
PROJECT_PATH="$(cd "$PROJECT_PATH" && pwd)"
CLEANUP_SCRIPT="$PROJECT_PATH/scripts/docker-cleanup.sh"

if [ ! -x "$CLEANUP_SCRIPT" ]; then
    echo "Error: $CLEANUP_SCRIPT is missing or not executable." >&2
    echo "The project path must be a checkout of this repository." >&2
    exit 1
fi

echo "Setting up automated Docker cleanup for: $PROJECT_PATH"

# Older versions of this script copied the cleanup script into the project
# root. The new job does not use that copy, and it blocks deploy-build.sh.
OLD_COPY="$PROJECT_PATH/docker-cleanup.sh"
if [ -e "$OLD_COPY" ]; then
    echo "Warning: $OLD_COPY is a copy from an older setup." >&2
    echo "The new cron job does not use it, and scripts/deploy-build.sh refuses" >&2
    echo "to build while this untracked file is present. Delete it." >&2
fi

# Create cron job
# Sanitize project name for safe filename usage
PROJECT_NAME=$(basename "$PROJECT_PATH" | sed 's/[^a-zA-Z0-9_-]/-/g' | sed 's/--*/-/g' | sed 's/^-//' | sed 's/-$//')
CRON_FILE="$CRON_DIR/docker-cleanup-${PROJECT_NAME}"
# Quote the path for the shell, so no part of it runs as a command.
printf -v PROJECT_PATH_Q '%q' "$PROJECT_PATH"

echo "Writing weekly cron job: $CRON_FILE"
{
    printf '#!/bin/bash\n'
    printf '# Weekly Docker cleanup for localize-pipeline\n'
    printf '# Auto-generated by scripts/setup-cron-cleanup.sh\n\n'
    printf 'cd %s && ./scripts/docker-cleanup.sh\n' "$PROJECT_PATH_Q"
} > "$CRON_FILE"
chmod +x "$CRON_FILE"

# Test the cleanup script
echo "Testing cleanup script..."
(cd "$PROJECT_PATH" && ./scripts/docker-cleanup.sh)

echo ""
echo "✅ Setup complete!"
echo ""
echo "Installed:"
echo "  - Cron job: $CRON_FILE (runs weekly)"
echo "  - It runs: $CLEANUP_SCRIPT"
echo ""
echo "Verify installation:"
echo "  - Check cron job: ls -lh $CRON_FILE"
echo "  - View logs: tail -50 $PROJECT_PATH/logs/docker-cleanup.log"
echo "  - Test manually: cd $PROJECT_PATH && ./scripts/docker-cleanup.sh"
